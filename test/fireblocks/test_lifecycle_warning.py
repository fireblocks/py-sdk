def test_helper_holds_no_module_level_logger():
    """The reason the helper survives dictConfig, asserted directly.

    logging.config.dictConfig defaults disable_existing_loggers=True and disables
    every logger already in loggerDict. A module-level `logging.getLogger(__name__)`
    is created at import, before the application configures logging, and would be
    disabled — silently, since .warning() then no-ops.

    The neighbouring connection_pool template acquires at module scope. Copying that
    convention here is exactly what would break this, so guard the deviation.
    """
    import fireblocks.lifecycle_warning as module

    module_level_loggers = [
        name
        for name, value in vars(module).items()
        if isinstance(value, logging.Logger)
    ]
    assert module_level_loggers == []


